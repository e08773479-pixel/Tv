  /* ============================================================
     25 — SUGGESTIONS
     ============================================================ */

  function suggest(query = "") {

    const normalized = normalizeArabic(query);

    if (!normalized) {
      return [
        "مين كان رئيس مصر وقت حرب أكتوبر؟",
        "إيه اللي حصل يوم 6 أكتوبر؟",
        "مين قائد القوات الجوية؟",
        "إيه حكاية الثغرة؟",
        "هاتلي خريطة حرب أكتوبر",
        "إيه اللي حصل بعد الحرب؟"
      ];
    }

    const searchResult = search(
      normalized,
      { limit: 5 }
    );

    const suggestions = [];

    searchResult.results.forEach(item => {

      const entry = item.entry;

      if (entry.type === "person") {
        suggestions.push(
          `مين هو ${entry.title}؟`
        );

        suggestions.push(
          `${entry.title} كان بيعمل إيه؟`
        );
      }

      if (
        entry.type === "major" ||
        entry.type === "battle" ||
        entry.type === "phase"
      ) {
        suggestions.push(
          `إيه اللي حصل في ${entry.title}؟`
        );

        if (entry.date) {
          suggestions.push(
            `${entry.title} حصل إمتى؟`
          );
        }
      }

      if (entry.type === "location") {
        suggestions.push(
          `فين ${entry.title}؟`
        );

        suggestions.push(
          `إيه أهميته في الحرب؟`
        );
      }
    });

    return unique(suggestions).slice(0, 8);
  }

  /* ============================================================
     26 — MAIN ASK API
     ============================================================ */

  function ask(query, context = {}) {

    const originalQuery = String(query || "").trim();

    if (!originalQuery) {
      return {
        answer:
          "اكتب سؤالك عن حرب أكتوبر 1973، وأنا هابحث في قاعدة المعرفة المحلية.",
        confidence: 0,
        entries: [],
        media: [],
        suggestions: suggest(""),
        intent: "empty"
      };
    }

    const special = specialAnswer(
      originalQuery,
      null
    );

    if (special) {

      const media =
        searchMedia(originalQuery);

      const result = {
        answer: special.answer,
        confidence: 0.99,
        entries: special.entry
          ? [special.entry]
          : [],
        media,
        suggestions: suggest(originalQuery),
        intent: detectIntent(originalQuery).intent
      };

      updateContext(
        {
          ...context,
          query: originalQuery,
          entityId:
            special.entry?.id ||
            context.entityId ||
            null
        },
        result
      );

      return result;
    }

    const searchResult = search(
      originalQuery,
      { limit: CONFIG.maxResults }
    );

    const top = searchResult.results[0];

    let confidence = 0;

    if (top) {
      confidence = Math.min(
        0.98,
        Math.max(
          0.18,
          top.score / 120
        )
      );
    }

    const entries = searchResult.results
      .map(x => x.entry);

    const mediaIntent =
      searchResult.intent.intent === "media" ||
      searchResult.intent.intent === "map" ||
      includesAny(
        originalQuery,
        [
          "صورة",
          "صوره",
          "صور",
          "خريطة",
          "خريطه",
          "خرائط"
        ]
      );

    const media = mediaIntent
      ? searchMedia(originalQuery)
      : [];

    if (!top || confidence < CONFIG.minConfidence) {

      const fallback = {
        answer:
          "مش لاقي في قاعدة المعرفة المحلية معلومات كافية للإجابة على السؤال ده بشكل موثوق. جرّب تصيغ السؤال بطريقة تانية، مثل: «مين السادات؟»، «إيه اللي حصل يوم 6 أكتوبر؟»، «الثغرة حصلت إمتى؟» أو «هاتلي خريطة».",
        confidence: 0.05,
        entries: [],
        media,
        suggestions: suggest(originalQuery),
        intent: searchResult.intent.intent
      };

      updateContext(
        {
          ...context,
          query: originalQuery
        },
        fallback
      );

      return fallback;
    }

    let answer = answerForEntry(
      top.entry,
      searchResult.intent.intent,
      originalQuery
    );

    /* ========================================================
       CONTEXTUAL FOLLOW-UP
       ======================================================== */

    const normalized = normalizeArabic(
      originalQuery
    );

    const isFollowUp =
      normalized === "ده" ||
      normalized === "دي" ||
      normalized === "هو" ||
      normalized === "هي" ||
      normalized.includes("كان بيعمل ايه") ||
      normalized.includes("كان بيعمل اي") ||
      normalized.includes("طب مين ده") ||
      normalized.includes("الصوره دي لمين") ||
      normalized.includes("الصورة دي لمين");

    if (
      isFollowUp &&
      contextIsAlive() &&
      CURRENT_CONTEXT.entityId
    ) {
      const contextualEntry =
        getEntry(CURRENT_CONTEXT.entityId);

      if (contextualEntry) {
        answer =
          `${contextualEntry.title}: ` +
          (
            contextualEntry.summary ||
            contextualEntry.body ||
            ""
          );
      }
    }

    const result = {
      answer,
      confidence,
      entries,
      media,
      suggestions: suggest(originalQuery),
      intent: searchResult.intent.intent,
      entities: searchResult.entities
        .slice(0, 5)
        .map(x => ({
          id: x.entry.id,
          title: x.entry.title,
          score: x.score
        }))
    };

    updateContext(
      {
        ...context,
        query: originalQuery,
        entityId:
          context.entityId ||
          top.entry.id
      },
      result
    );

    return result;
  }

