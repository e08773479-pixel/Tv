  /* ============================================================
     23 — ANSWER GENERATION
     ============================================================ */

  function answerForEntry(entry, intent, query) {

    if (!entry) {
      return "";
    }

    if (
      intent === "date" &&
      entry.date
    ) {
      return `${entry.title} ارتبط بـ ${entry.date}. ${
        entry.summary || ""
      }`;
    }

    if (
      intent === "location"
    ) {
      return `${entry.title}: ${
        entry.summary || entry.body || ""
      }`;
    }

    if (
      intent === "role" &&
      entry.type === "person"
    ) {
      const roles = entry.roles || [];

      if (roles.length) {
        return `${entry.title} كان ${
          roles.join("، ")
        }. ${entry.summary || ""}`;
      }
    }

    if (
      intent === "person" &&
      entry.type === "person"
    ) {
      return `${entry.title}: ${
        entry.summary || entry.body || ""
      }`;
    }

    if (
      intent === "aftermath"
    ) {
      return `${entry.title}: ${
        entry.body || entry.summary || ""
      }`;
    }

    if (
      intent === "definition"
    ) {
      return `${entry.title}: ${
        entry.summary || entry.body || ""
      }`;
    }

    return entry.body ||
      entry.summary ||
      `${entry.title} — لا توجد تفاصيل إضافية في هذه الوحدة.`;
  }

