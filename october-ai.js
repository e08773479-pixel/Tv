  function extractEntities(query) {
    const normalized = normalizeArabic(query);
    const matches = [];

    DATABASE.forEach(entry => {

      const terms = [
        entry.title,
        entry.shortTitle,
        ...(entry.aliases || [])
      ]
        .filter(Boolean)
        .map(normalizeArabic);

      let best = 0;
      let matchedTerm = "";

      terms.forEach(term => {
        if (!term) return;

        if (normalized === term) {
          best = Math.max(best, 1);
          matchedTerm = term;
          return;
        }

        if (normalized.includes(term)) {
          const score = 0.92;

          if (score > best) {
            best = score;
            matchedTerm = term;
          }

          return;
        }

        const tokens = tokenize(normalized);

        if (
          tokens.length === 1 &&
          similarity(tokens[0], term) >= 0.72
        ) {
          const score = 0.72;

          if (score > best) {
            best = score;
            matchedTerm = term;
          }
        }
      });

      if (best > 0) {
        matches.push({
          entry,
          score: best,
          matchedTerm
        });
      }
    });

    return matches.sort((a, b) => b.score - a.score);
  }

  /* ============================================================
     17 — SEARCH SCORING
     ============================================================ */

  function scoreEntry(entry, query, intentInfo) {
    const normalizedQuery = normalizeArabic(query);
    const queryTokens = tokenize(normalizedQuery);

    let score = 0;
    const reasons = [];

    const title = normalizeArabic(entry.title || "");

    if (normalizedQuery === title) {
      score += 100;
      reasons.push("exact-title");
    } else if (normalizedQuery.includes(title)) {
      score += 70;
      reasons.push("title");
    }

    for (const alias of entry.aliases || []) {
      const a = normalizeArabic(alias);

      if (normalizedQuery === a) {
        score += 90;
        reasons.push("exact-alias");
      } else if (normalizedQuery.includes(a)) {
        score += 62;
        reasons.push("alias");
      } else {
        const sim = similarity(normalizedQuery, a);

        if (sim > 0.76) {
          score += sim * 24;
          reasons.push("fuzzy-alias");
        }
      }
    }

    for (const keyword of entry.keywords || []) {
      const k = normalizeArabic(keyword);

      if (normalizedQuery.includes(k)) {
        score += 13;
        reasons.push("keyword");
      }
    }

    const body = normalizeArabic(
      `${entry.summary || ""} ${entry.body || ""}`
    );

    queryTokens.forEach(token => {
      if (token.length < 2) return;

      if (body.includes(token)) {
        score += 2.5;
        reasons.push("body-token");
      }
    });

    if (
      intentInfo.intent === "person" &&
      entry.type === "person"
    ) {
      score += 24;
      reasons.push("person-intent");
    }

    if (
      intentInfo.intent === "role" &&
      entry.type === "person"
    ) {
      score += 20;
      reasons.push("role-intent");
    }

    if (
      intentInfo.intent === "date" &&
      entry.date
    ) {
      score += 18;
      reasons.push("date-intent");
    }

    if (
      intentInfo.intent === "location" &&
      (
        entry.type === "location" ||
        entry.locations?.length
      )
    ) {
      score += 18;
      reasons.push("location-intent");
    }

    if (
      intentInfo.intent === "event" &&
      (
        entry.type === "major" ||
        entry.type === "battle" ||
        entry.type === "phase"
      )
    ) {
      score += 20;
      reasons.push("event-intent");
    }

    if (
      intentInfo.intent === "aftermath" &&
      entry.type === "aftermath"
    ) {
      score += 40;
      reasons.push("aftermath-intent");
    }

    return {
      score,
      reasons
    };
  }

  /* ============================================================
     18 — CONTEXT BOOST
     ============================================================ */

  function applyContextBoost(entry, query, rawScore) {
    if (!contextIsAlive()) {
      return rawScore;
    }

    let score = rawScore;

    if (
      CURRENT_CONTEXT.entityId &&
      entry.id === CURRENT_CONTEXT.entityId
    ) {
      score += 48;
    }

    if (
      CURRENT_CONTEXT.lastEntries.includes(entry.id)
    ) {
      score += 18;
    }

    if (
      CURRENT_CONTEXT.selectedMediaId &&
      entry.media?.includes(
        CURRENT_CONTEXT.selectedMediaId
      )
    ) {
      score += 32;
    }

    const shortQuery = normalizeArabic(query);

    if (
      ["ده", "دي", "دا", "هذا", "هذه", "هو", "هي"]
        .some(x => shortQuery === normalizeArabic(x))
    ) {
      if (CURRENT_CONTEXT.entityId) {
        score += 80;
      }
    }

    return score;
  }

  /* ============================================================
     19 — SEARCH ENGINE
     ============================================================ */

  function search(query, options = {}) {
    const intentInfo = detectIntent(query);

    const entityMatches = extractEntities(query);

    const hard = hardAliasMatch(query);

    const results = DATABASE
      .map(entry => {

        const scored = scoreEntry(
          entry,
          query,
          intentInfo
        );

        const contextScore = applyContextBoost(
          entry,
          query,
          scored.score
        );

        return {
          entry,
          score: contextScore,
          reasons: scored.reasons
        };
      })
      .filter(item => item.score >= 1)
      .sort((a, b) => b.score - a.score);

    if (hard) {
      const index = results.findIndex(
        x => x.entry.id === hard.entry.id
      );

      if (index >= 0) {
        results[index].score += 100;
      } else {
        results.unshift({
          entry: hard.entry,
          score: 150,
          reasons: ["hard-alias"]
        });
      }
    }

    entityMatches.slice(0, 5).forEach(match => {
      const index = results.findIndex(
        x => x.entry.id === match.entry.id
      );

      if (index >= 0) {
        results[index].score +=
          match.score * 30;
      }
    });

    const maxResults =
      options.limit ||
      CONFIG.maxResults;

    return {
      intent: intentInfo,
      entities: entityMatches,
      results: results.slice(0, maxResults)
    };
  }

  /* ============================================================
     20 — MEDIA SEARCH
     ============================================================ */

  function searchMedia(query, options = {}) {
    const normalized = normalizeArabic(query);
    const tokens = tokenize(normalized);

    const scored = MEDIA.map(media => {

      const haystack = normalizeArabic(
        [
          media.title,
          media.description,
          ...(media.tags || []),
          ...(media.queryTags || [])
        ].join(" ")
      );

      let score = 0;

      if (haystack.includes(normalized)) {
        score += 80;
      }

      tokens.forEach(token => {
        if (token.length > 1 && haystack.includes(token)) {
          score += 8;
        }
      });

      if (
        media.type === "map" &&
        includesAny(normalized, [
          "خريطة",
          "خريطه",
          "خرائط"
        ])
      ) {
        score += 50;
      }

      if (
        media.type === "photo" &&
        includesAny(normalized, [
          "صورة",
          "صوره",
          "صور"
        ])
      ) {
        score += 30;
      }

      return {
        media,
        score
      };

    })
      .filter(x => x.score > 0)
      .sort((a, b) => b.score - a.score);

    return scored
      .slice(0, options.limit || 8)
      .map(x => x.media);
  }

