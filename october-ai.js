  function searchByLocation(locationName) {

    const normalized =
      normalizeArabic(locationName);

    return DATABASE.filter(entry => {

      const locations = [
        entry.title,
        ...(entry.locations || []),
        ...(entry.keywords || [])
      ]
        .filter(Boolean)
        .map(normalizeArabic);

      return locations.some(
        value =>
          value.includes(normalized) ||
          normalized.includes(value)
      );
    });
  }

  /* ============================================================
     33 — PERSON → EVENTS
     ============================================================ */

  function eventsForPerson(personId) {

    return EVENTS.filter(
      event =>
        event.people?.includes(personId)
    );
  }

  /* ============================================================
     34 — EVENT → PEOPLE
     ============================================================ */

  function peopleForEvent(eventId) {

    const event =
      getEntry(eventId);

    if (!event) return [];

    return (event.people || [])
      .map(id => getEntry(id))
      .filter(Boolean);
  }

  /* ============================================================
     35 — EVENT → MEDIA
     ============================================================ */

  function mediaForEntry(entryId) {

    const entry =
      getEntry(entryId);

    if (!entry) return [];

    return getMedia(
      entry.media || []
    );
  }

