  function expandQuery(query) {

    const normalized =
      normalizeArabic(query);

    const expanded = [
      normalized
    ];

    Object.entries(
      QUERY_EXPANSIONS
    ).forEach(([key, values]) => {

      if (
        normalized.includes(
          normalizeArabic(key)
        )
      ) {
        expanded.push(
          ...values.map(normalizeArabic)
        );
      }
    });

    return unique(expanded);
  }

  /* ============================================================
     37 — DEEP SEARCH
     ============================================================ */

  function deepSearch(query) {

    const expanded =
      expandQuery(query);

    const merged = new Map();

    expanded.forEach(q => {

      const result =
        search(q, {
          limit: 15
        });

      result.results.forEach(item => {

        const id =
          item.entry.id;

        const current =
          merged.get(id);

        if (!current) {

          merged.set(id, {
            entry: item.entry,
            score: item.score,
            hits: 1
          });

        } else {

          current.score += item.score;
          current.hits += 1;
        }
      });
    });

    return [...merged.values()]
      .sort((a, b) => {

        const scoreA =
          a.score + a.hits * 12;

        const scoreB =
          b.score + b.hits * 12;

        return scoreB - scoreA;
      })
      .slice(0, 12);
  }

  /* ============================================================
     38 — SMART ASK
     ============================================================ */

  function smartAsk(query, context = {}) {

    const deep =
      deepSearch(query);

    const basic =
      ask(query, context);

    if (
      basic.confidence >= 0.7
    ) {
      return basic;
    }

    if (
      deep.length &&
      deep[0].score > 20
    ) {

      const top =
        deep[0].entry;

      const result = {
        answer:
          answerForEntry(
            top,
            detectIntent(query).intent,
            query
          ),
        confidence:
          Math.min(
            0.88,
            deep[0].score / 130
          ),
        entries:
          deep.slice(0, 8)
            .map(x => x.entry),
        media:
          searchMedia(query),
        suggestions:
          suggest(query),
        intent:
          detectIntent(query).intent
      };

      updateContext(
        {
          ...context,
          query,
          entityId:
            context.entityId ||
            top.id
        },
        result
      );

      return result;
    }

    return basic;
  }

